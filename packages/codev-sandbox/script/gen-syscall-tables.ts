// Regenerates src/seccomp/syscalls-{x64,arm64}.ts from the kernel uapi headers
// installed on a Linux host (linux-libc-dev). Run with bun from this package.
//
// The seccomp policy names syscalls; the filter needs numbers, and those are
// per-architecture below 424 (x86_64 keeps its historical table, arm64 uses
// the asm-generic one). Above 424 every architecture shares one numbering, so
// syscalls newer than the installed headers are appended from UNIFIED_TAIL
// rather than lost — a policy entry that names one of them must still resolve.
import { spawnSync } from "node:child_process"
import { mkdtempSync, rmSync, writeFileSync } from "node:fs"
import { tmpdir } from "node:os"
import { join } from "node:path"

const UNIFIED_TAIL: Record<string, number> = {
  futex_waitv: 449,
  set_mempolicy_home_node: 450,
  cachestat: 451,
  fchmodat2: 452,
  map_shadow_stack: 453,
  futex_wake: 454,
  futex_wait: 455,
  futex_requeue: 456,
  statmount: 457,
  listmount: 458,
  lsm_get_self_attr: 459,
  lsm_set_self_attr: 460,
  lsm_list_modules: 461,
  mseal: 462,
  setxattrat: 463,
  getxattrat: 464,
  listxattrat: 465,
  removexattrat: 466,
}

const ARCHES = {
  x64: { header: "asm/unistd_64.h", defines: [] as string[] },
  arm64: {
    header: "asm-generic/unistd.h",
    // What arch/arm64/include/uapi/asm/unistd.h sets before including the
    // generic table; the 32-bit-only ones are omitted since __BITS_PER_LONG=64.
    defines: [
      "__BITS_PER_LONG=64",
      "__ARCH_WANT_RENAMEAT",
      "__ARCH_WANT_NEW_STAT",
      "__ARCH_WANT_SET_GET_RLIMIT",
      "__ARCH_WANT_SYS_CLONE3",
      "__ARCH_WANT_MEMFD_SECRET",
    ],
  },
}

function generate(arch: keyof typeof ARCHES) {
  const spec = ARCHES[arch]
  const flags = spec.defines.map((define) => `-D${define}`)
  const macros = spawnSync("cpp", ["-dM", ...flags, "-"], { input: `#include <${spec.header}>\n`, encoding: "utf8" })
  if (macros.status !== 0) throw new Error(`cpp failed for ${arch}: ${macros.stderr}`)
  const names = [...macros.stdout.matchAll(/^#define __NR_(\w+)/gm)]
    .map((match) => match[1])
    .filter((name) => name !== "syscalls" && name !== "arch_specific_syscall" && !name.startsWith("3264"))
  // Numbers come out of the compiler, not a regex: the generic table defines
  // many entries through __NR3264_* aliases that only the preprocessor resolves.
  const dir = mkdtempSync(join(tmpdir(), "codev-syscalls-"))
  const source = join(dir, "print.c")
  writeFileSync(
    source,
    [
      `#include <stdio.h>`,
      `#include <${spec.header}>`,
      `int main(void) {`,
      ...names.map((name) => `  printf("${name} %d\\n", (int)__NR_${name});`),
      `  return 0;`,
      `}`,
    ].join("\n"),
  )
  const binary = join(dir, "print")
  const compiled = spawnSync("cc", [...flags, "-o", binary, source], { encoding: "utf8" })
  if (compiled.status !== 0) throw new Error(`cc failed for ${arch}: ${compiled.stderr}`)
  const printed = spawnSync(binary, [], { encoding: "utf8" })
  rmSync(dir, { recursive: true, force: true })
  const table = new Map<string, number>(
    printed.stdout
      .trim()
      .split("\n")
      .map((line) => {
        const [name, number] = line.split(" ")
        return [name, Number(number)] as const
      }),
  )
  for (const [name, number] of Object.entries(UNIFIED_TAIL)) {
    if (!table.has(name)) table.set(name, number)
  }
  const entries = [...table.entries()].sort((a, b) => a[1] - b[1])
  const body = entries.map(([name, number]) => `  ${name}: ${number},`).join("\n")
  return `// Generated by script/gen-syscall-tables.ts from the ${spec.header} uapi header;\n// do not edit by hand. Syscall numbers for ${arch === "x64" ? "x86_64" : "aarch64"}.\nexport const SYSCALLS_${arch.toUpperCase()}: Record<string, number> = {\n${body}\n}\n`
}

for (const arch of Object.keys(ARCHES) as (keyof typeof ARCHES)[]) {
  const target = join(import.meta.dirname, "..", "src", "seccomp", `syscalls-${arch}.ts`)
  writeFileSync(target, generate(arch))
  console.log(`wrote ${target}`)
}
