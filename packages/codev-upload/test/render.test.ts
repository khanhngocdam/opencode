import { describe, expect, test } from "bun:test"
import { codeFence, renderMarkdown, titleFromFirstMessage } from "../src/render"
import type { Session } from "../src/types"

// Golden fixtures: the expected strings pin the hub's renderMarkdown output
// (hub src/lib/markdown.ts) byte for byte. If one of these fails after an
// intentional format change, the hub's renderer must change in the same
// release — the backend dedups by content hash, so drift re-uploads every
// session as a new version.

function fixtureSession(overrides: Partial<Session> = {}): Session {
  return {
    id: "ses_abc",
    createdAt: new Date("2026-08-01T10:00:00.000Z"),
    updatedAt: new Date("2026-08-01T10:30:00.000Z"),
    title: "Fix the flaky test",
    firstUserMessage: "please fix the flaky test",
    projectDir: "/tmp/project",
    messages: [
      { role: "user", content: "please fix the flaky test", timestamp: "2026-08-01T10:00:00.000Z" },
      {
        role: "assistant",
        content: "Done, the test is fixed.",
        timestamp: "2026-08-01T10:05:00.000Z",
        model: "claude-sonnet-4-5",
      },
    ],
    ...overrides,
  }
}

describe("renderMarkdown", () => {
  test("renders the hub's exact format", () => {
    expect(renderMarkdown(fixtureSession())).toBe(
      [
        "<!-- Generated by CoDev -->",
        "",
        "# Fix the flaky test",
        "",
        "<!-- codev-code Session ses_abc (2026-08-01T10:00:00.000Z) -->",
        "",
        "## User",
        "",
        "please fix the flaky test",
        "",
        "---",
        "",
        "## Assistant (claude-sonnet-4-5)",
        "",
        "Done, the test is fixed.",
        "",
      ]
        .join("\n")
        .trimEnd() + "\n",
    )
  })

  test("embeds base_url and subagent char tags in the session comment", () => {
    const md = renderMarkdown(
      fixtureSession({ baseUrl: "https://gw.test/v1", subagentCharsIn: 12, subagentCharsOut: 34 }),
    )
    expect(md).toContain(
      "<!-- codev-code Session ses_abc (2026-08-01T10:00:00.000Z) base_url=https://gw.test/v1 subagent_chars_in=12 subagent_chars_out=34 -->",
    )
  })

  test("falls back to first message then timestamp for the title", () => {
    const noTitle = renderMarkdown(fixtureSession({ title: undefined }))
    expect(noTitle).toContain("# please fix the flaky test")
    const bare = renderMarkdown(fixtureSession({ title: undefined, firstUserMessage: undefined }))
    expect(bare).toContain("# 2026-08-01 10:00:00Z")
  })

  test("untitled assistant turns render a bare heading", () => {
    const md = renderMarkdown(fixtureSession({ messages: [{ role: "assistant", content: "hello" }] }))
    expect(md).toContain("## Assistant\n")
    expect(md).not.toContain("## Assistant (")
  })
})

describe("titleFromFirstMessage", () => {
  test("collapses whitespace and truncates at a word boundary with ellipsis", () => {
    expect(titleFromFirstMessage("  fix\n\nthe   test ")).toBe("fix the test")
    const long = `${"word ".repeat(20)}tail`
    const title = titleFromFirstMessage(long)
    expect(title?.length).toBeLessThanOrEqual(81)
    expect(title?.endsWith("…")).toBe(true)
  })
})

describe("codeFence", () => {
  test("uses a fence longer than any embedded backtick run", () => {
    expect(codeFence("plain", "bash")).toBe("```bash\nplain\n```")
    expect(codeFence("has ``` inside")).toBe("````\nhas ``` inside\n````")
  })
})
