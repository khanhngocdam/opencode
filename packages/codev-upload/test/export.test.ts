import { Database } from "bun:sqlite"
import { afterEach, beforeEach, describe, expect, test } from "bun:test"
import { mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import { tmpdir } from "node:os"
import { join } from "node:path"
import { runExport } from "../src/export"
import { agentLogsDir, projectFolderName, sessionDbPath } from "../src/paths"

let tempDir: string
let originalTestHome: string | undefined
let originalXdgData: string | undefined

beforeEach(() => {
  tempDir = mkdtempSync(join(tmpdir(), "codev-upload-export-"))
  originalTestHome = process.env.CODEV_TEST_HOME
  originalXdgData = process.env.XDG_DATA_HOME
  process.env.CODEV_TEST_HOME = tempDir
  process.env.XDG_DATA_HOME = join(tempDir, "share")
})

afterEach(() => {
  if (originalTestHome === undefined) delete process.env.CODEV_TEST_HOME
  else process.env.CODEV_TEST_HOME = originalTestHome
  if (originalXdgData === undefined) delete process.env.XDG_DATA_HOME
  else process.env.XDG_DATA_HOME = originalXdgData
  rmSync(tempDir, { recursive: true, force: true })
})

// Fixture store matching the session schema the reader queries (the same
// tables the hub's external reader consumes).
function seedDb(seed: (db: Database) => void): void {
  mkdirSync(join(tempDir, "share", "codev"), { recursive: true })
  const db = new Database(sessionDbPath(), { create: true })
  db.run("CREATE TABLE project (id TEXT PRIMARY KEY, worktree TEXT)")
  db.run(
    "CREATE TABLE session (id TEXT PRIMARY KEY, project_id TEXT, title TEXT, directory TEXT, parent_id TEXT, time_created INTEGER, time_updated INTEGER)",
  )
  db.run("CREATE TABLE message (id TEXT PRIMARY KEY, session_id TEXT, time_created INTEGER, data TEXT)")
  db.run("CREATE TABLE part (id TEXT PRIMARY KEY, session_id TEXT, message_id TEXT, time_created INTEGER, data TEXT)")
  seed(db)
  db.close()
}

const T0 = Date.UTC(2026, 7, 1, 10, 0, 0)

function insertMessage(db: Database, sessionId: string, id: string, time: number, meta: object): void {
  db.run("INSERT INTO message (id, session_id, time_created, data) VALUES (?, ?, ?, ?)", [
    id,
    sessionId,
    time,
    JSON.stringify(meta),
  ])
}

function insertPart(db: Database, sessionId: string, messageId: string, id: string, time: number, data: object): void {
  db.run("INSERT INTO part (id, session_id, message_id, time_created, data) VALUES (?, ?, ?, ?, ?)", [
    id,
    sessionId,
    messageId,
    time,
    JSON.stringify(data),
  ])
}

describe("runExport", () => {
  test("exports sessions into the hub layout with hub-format markdown", async () => {
    const projectDir = join(tempDir, "work", "myproj")
    mkdirSync(projectDir, { recursive: true })
    seedDb((db) => {
      db.run("INSERT INTO project (id, worktree) VALUES ('prj1', ?)", [projectDir])
      db.run(
        "INSERT INTO session (id, project_id, title, directory, parent_id, time_created, time_updated) VALUES ('ses1', 'prj1', 'My session', ?, NULL, ?, ?)",
        [projectDir, T0, T0 + 60_000],
      )
      insertMessage(db, "ses1", "m1", T0, { role: "user" })
      insertPart(db, "ses1", "m1", "p1", T0, { type: "text", text: "hello agent" })
      insertMessage(db, "ses1", "m2", T0 + 30_000, { role: "assistant", modelID: "claude-sonnet-4-5" })
      insertPart(db, "ses1", "m2", "p2", T0 + 30_000, { type: "text", text: "hello user" })
      insertPart(db, "ses1", "m2", "p3", T0 + 31_000, {
        type: "tool",
        tool: "bash",
        state: { status: "completed", input: { command: "ls" }, output: "file.txt" },
      })
    })

    const summary = await await runExport()
    expect(summary.exported).toBe(1)
    expect(summary.projects).toBe(1)

    const agentDir = join(agentLogsDir(), projectFolderName(projectDir), "codev-code")
    const files = readdirSync(agentDir)
    expect(files).toEqual(["2026-08-01_10-00-00Z-hello-agent.md"])

    const md = readFileSync(join(agentDir, files[0]), "utf-8")
    expect(md).toBe(
      [
        "<!-- Generated by CoDev -->",
        "",
        "# My session",
        "",
        "<!-- codev-code Session ses1 (2026-08-01T10:00:00.000Z) -->",
        "",
        "## User",
        "",
        "hello agent",
        "",
        "---",
        "",
        "## Assistant (claude-sonnet-4-5)",
        "",
        "hello user",
        '<tool-use data-tool-type="shell" data-tool-name="bash">',
        "<details>",
        "<summary>Run command: ls</summary>",
        "",
        "```bash",
        "$ ls",
        "file.txt",
        "```",
        "</details>",
        "</tool-use>",
        "",
      ].join("\n"),
    )

    const stats = JSON.parse(
      readFileSync(join(agentLogsDir(), projectFolderName(projectDir), "statistics.json"), "utf-8"),
    )
    expect(stats.sessions.ses1.user_message_count).toBe(1)
    expect(stats.sessions.ses1.agent_message_count).toBe(1)
    expect(stats.sessions.ses1.provider).toBe("codev-code")
  })

  test("skips subagent sessions but rolls their chars into the parent", async () => {
    const projectDir = join(tempDir, "work", "proj2")
    mkdirSync(projectDir, { recursive: true })
    seedDb((db) => {
      db.run("INSERT INTO project (id, worktree) VALUES ('prj1', ?)", [projectDir])
      db.run(
        "INSERT INTO session (id, project_id, title, directory, parent_id, time_created, time_updated) VALUES ('parent', 'prj1', NULL, ?, NULL, ?, ?)",
        [projectDir, T0, T0],
      )
      db.run(
        "INSERT INTO session (id, project_id, title, directory, parent_id, time_created, time_updated) VALUES ('child', 'prj1', NULL, ?, 'parent', ?, ?)",
        [projectDir, T0, T0],
      )
      insertMessage(db, "parent", "m1", T0, { role: "user" })
      insertPart(db, "parent", "m1", "p1", T0, { type: "text", text: "spawn a subagent" })
      insertMessage(db, "child", "cm1", T0, { role: "assistant", modelID: "m" })
      insertPart(db, "child", "cm1", "cp1", T0, { type: "text", text: "12345" })
    })

    const summary = await await runExport()
    expect(summary.exported).toBe(1)
    const agentDir = join(agentLogsDir(), projectFolderName(projectDir), "codev-code")
    const md = readFileSync(join(agentDir, readdirSync(agentDir)[0]), "utf-8")
    expect(md).toContain("subagent_chars_out=5")
  })

  test("global (VCS-less) sessions use their own directory; sessions without one are skipped", async () => {
    const looseDir = join(tempDir, "loose")
    mkdirSync(looseDir, { recursive: true })
    seedDb((db) => {
      db.run(
        "INSERT INTO session (id, project_id, title, directory, parent_id, time_created, time_updated) VALUES ('g1', 'global', NULL, ?, NULL, ?, ?)",
        [looseDir, T0, T0],
      )
      db.run(
        "INSERT INTO session (id, project_id, title, directory, parent_id, time_created, time_updated) VALUES ('g2', 'global', NULL, NULL, NULL, ?, ?)",
        [T0, T0],
      )
      insertMessage(db, "g1", "m1", T0, { role: "user" })
      insertPart(db, "g1", "m1", "p1", T0, { type: "text", text: "loose session" })
      insertMessage(db, "g2", "m2", T0, { role: "user" })
      insertPart(db, "g2", "m2", "p2", T0, { type: "text", text: "orphan" })
    })

    const summary = await await runExport()
    expect(summary.exported).toBe(1)
    expect(readdirSync(join(agentLogsDir(), projectFolderName(looseDir), "codev-code"))).toHaveLength(1)
  })

  test("stamps base_url from the CoDev-managed codev.json", async () => {
    const projectDir = join(tempDir, "work", "proj3")
    mkdirSync(projectDir, { recursive: true })
    const configDir = join(tempDir, ".config", "codev")
    mkdirSync(configDir, { recursive: true })
    writeFileSync(
      join(configDir, "codev.json"),
      JSON.stringify({ provider: { netgate: { options: { baseURL: "https://gw.test/v1" } } } }),
    )
    seedDb((db) => {
      db.run("INSERT INTO project (id, worktree) VALUES ('prj1', ?)", [projectDir])
      db.run(
        "INSERT INTO session (id, project_id, title, directory, parent_id, time_created, time_updated) VALUES ('ses1', 'prj1', NULL, ?, NULL, ?, ?)",
        [projectDir, T0, T0],
      )
      insertMessage(db, "ses1", "m1", T0, { role: "user" })
      insertPart(db, "ses1", "m1", "p1", T0, { type: "text", text: "hi" })
    })

    await runExport()
    const agentDir = join(agentLogsDir(), projectFolderName(projectDir), "codev-code")
    const md = readFileSync(join(agentDir, readdirSync(agentDir)[0]), "utf-8")
    expect(md).toContain("base_url=https://gw.test/v1")
  })

  test("a missing store exports nothing and reports where it looked", async () => {
    const summary = await await runExport()
    expect(summary.exported).toBe(0)
    expect(summary.dbPath).toBe(sessionDbPath())
  })
})
