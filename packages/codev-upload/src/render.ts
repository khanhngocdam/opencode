import type { Session } from "./types"

// Byte-for-byte port of the hub's src/lib/markdown.ts, fixed to the
// codev-code agent label. Any drift here breaks the coexistence story: the
// backend dedups by content hash, so a one-character difference re-uploads
// every session as a new version.

const HEADER = "<!-- Generated by CoDev -->"
const AGENT_LABEL = "codev-code"

/**
 * Derive a display title from the first user message when the session stores
 * none. Collapses whitespace, truncates to 80 chars at a word boundary, and
 * appends "…" when cut (hub parity).
 */
export function titleFromFirstMessage(msg: string): string | undefined {
  const clean = msg.replace(/\s+/g, " ").trim()
  if (!clean) return undefined
  if (clean.length <= 80) return clean
  const cut = clean.slice(0, 80)
  const lastSpace = cut.lastIndexOf(" ")
  return `${lastSpace > 20 ? cut.slice(0, lastSpace) : cut}…`
}

export function renderMarkdown(session: Session): string {
  const lines: string[] = []
  lines.push(HEADER, "")
  const title =
    session.title ||
    (session.firstUserMessage ? titleFromFirstMessage(session.firstUserMessage) : undefined) ||
    formatTitleTimestamp(session.createdAt)
  lines.push(`# ${title}`)
  lines.push("")
  // base_url in the session comment is how the worker tells internal from
  // external model usage; subagent_chars_* carry folded-in child costs.
  const baseUrlTag = session.baseUrl ? ` base_url=${session.baseUrl}` : ""
  const subagentTag =
    session.subagentCharsIn || session.subagentCharsOut
      ? ` subagent_chars_in=${session.subagentCharsIn ?? 0} subagent_chars_out=${session.subagentCharsOut ?? 0}`
      : ""
  lines.push(
    `<!-- ${AGENT_LABEL} Session ${session.id} (${session.createdAt.toISOString()})${baseUrlTag}${subagentTag} -->`,
  )
  lines.push("")

  let isFirst = true
  for (const msg of session.messages) {
    if (!isFirst) {
      lines.push("---", "")
    }
    isFirst = false
    const heading = msg.role === "user" ? "## User" : msg.model ? `## Assistant (${msg.model})` : "## Assistant"
    lines.push(heading, "")
    lines.push(msg.content.trimEnd(), "")
  }

  return `${lines.join("\n").trimEnd()}\n`
}

// Picks a fence longer than any backtick run in `content` so embedded
// triple-backticks can't break out of the block (hub parity).
export function codeFence(content: string, lang = ""): string {
  let max = 2
  const re = /`{3,}/g
  let m: RegExpExecArray | null = re.exec(content)
  while (m !== null) {
    if (m[0].length > max) max = m[0].length
    m = re.exec(content)
  }
  const fence = "`".repeat(max + 1)
  return `${fence}${lang}\n${content}\n${fence}`
}

function formatTitleTimestamp(date: Date): string {
  const pad = (n: number) => String(n).padStart(2, "0")
  return (
    `${date.getUTCFullYear()}-${pad(date.getUTCMonth() + 1)}-${pad(date.getUTCDate())} ` +
    `${pad(date.getUTCHours())}:${pad(date.getUTCMinutes())}:${pad(date.getUTCSeconds())}Z`
  )
}
